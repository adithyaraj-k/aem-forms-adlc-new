#!/usr/bin/env node
/**
 * sync-agent-routing.mjs — generate every per-tool agent shim from a single source.
 *
 * Read this top-to-bottom; each numbered section is self-contained and does
 * exactly one job. Skim the "WHAT THIS SCRIPT DOES" list, then jump straight
 * to the section you care about.
 *
 * SOURCES OF TRUTH (read-only, never written by this script):
 *   .claude/agents/<name>/AGENT.md — the agent roster + all prompt logic + Claude models
 *                                    (one folder per agent; a flat .claude/agents/<name>.md
 *                                    is also accepted, for other repos' layouts)
 *   scripts/.agent-routing.json    — role tier per agent, and model per tool per tier
 *
 * GENERATED (safe to delete — the next run recreates them):
 *   AGENTS.md                       — the routing matrix block, between markers
 *   .github/agents/<name>.agent.md  — Copilot CLI custom agents (pointer shims)
 *   .codex/agents/<name>.toml       — Codex CLI custom agents (pointer shims)
 *
 * WHAT THIS SCRIPT DOES, IN ORDER:
 *   1. Load scripts/.agent-routing.json (tiers + per-tool models).
 *   2. Discover the agent roster from .claude/agents/*.md.
 *   3. Build ONE shared instructions text per agent (SAME wording for every
 *      tool) and hand it to a per-format "renderer" that wraps it in that
 *      tool's file syntax (YAML frontmatter+Markdown, or TOML).
 *   4. Write each rendered shim to disk (idempotently — see below).
 *   5. Delete shims whose agent no longer exists ("orphans").
 *   6. Regenerate the Model Routing Matrix in AGENTS.md.
 *   7. Print a summary; exit non-zero if anything is wrong or (in --check) drifted.
 *
 * WHY IT'S GENERIC: adding a new LLM tool never means writing a new renderer.
 * Every tool declares which *format* its agent files use (`"frontmatter-md"`
 * or `"toml"` — see FORMAT_RENDERERS below), plus its own model/description
 * metadata in scripts/.agent-routing.json. The renderer injects that metadata around
 * the exact same instructions text, so two shims for the same agent always
 * read the same — only the model line(s) and file syntax differ. A genuinely
 * new file shape (not frontmatter-md or toml) needs one new renderer function;
 * everything else about it (agent discovery, idempotency, orphan cleanup,
 * reporting) is already generic and reused automatically.
 *
 * IDEMPOTENCY: by default this script never touches a shim file that already
 * exists on disk — it only creates files that are missing. This makes it safe
 * to "generate again": existing, possibly hand-tweaked, agent shims are left
 * alone. Use --force to make it a true sync again (overwrite drifted shims and
 * prune orphans to match the source of truth). --check never writes; it only
 * reports drift, for CI.
 *
 * Usage:
 *   node scripts/sync-agent-routing.mjs           # create missing shims only
 *   node scripts/sync-agent-routing.mjs --force   # also overwrite existing/drifted shims
 *   node scripts/sync-agent-routing.mjs --check   # verify in sync, exit 1 if not (no writes)
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CLAUDE_AGENTS_DIR = join(ROOT, '.claude', 'agents');
const ROUTING_FILE = join(ROOT, 'scripts', '.agent-routing.json');
const AGENTS_MD = join(ROOT, 'AGENTS.md');

const MATRIX_BEGIN = '<!-- BEGIN:AGENT-ROUTING (generated by scripts/sync-agent-routing.mjs — do not edit by hand) -->';
const MATRIX_END = '<!-- END:AGENT-ROUTING -->';

// CLI flags — see the "Usage" block in the header comment above.
const FLAGS = {
  checkOnly: process.argv.includes('--check'), // report drift only, never write
  force: process.argv.includes('--force'), // overwrite existing shims + prune orphans
};

/** Relative path for display, independent of OS path separators. */
function displayPath(absolutePath) {
  return absolutePath.replace(ROOT + '\\', '').replace(ROOT + '/', '').replace(/\\/g, '/');
}

// =============================================================================
// 1. Load the routing manifest (scripts/.agent-routing.json)
// =============================================================================

function loadRoutingConfig() {
  const routing = JSON.parse(readFileSync(ROUTING_FILE, 'utf8'));
  return {
    agentTiers: routing.agentTiers, // { agentName: tierKey }
    tierLabels: routing.tierLabels, // { tierKey: "Human Label" }
    adlcStages: routing.adlcStages, // { agentName: "ADLC stage" }
    tools: routing.tools, // { toolKey: { label, emit, models, ... } }
  };
}

// =============================================================================
// 2. Discover the agent roster from .claude/agents/ (the source of truth)
// =============================================================================
//
// Each entry under .claude/agents/ is either:
//   - a folder   .claude/agents/<name>/AGENT.md   (this repo's layout — one folder
//     per agent, which may also hold non-prompt assets like a diagram .svg)
//   - a flat file .claude/agents/<name>.md         (accepted too, for repos that
//     lay agents out that way instead)
// Anything else (e.g. the `runs/` run-record directory, which has no AGENT.md)
// is silently skipped — it isn't an agent.

/** Minimal YAML frontmatter reader: only the flat scalar keys we need. */
function readFrontmatter(text) {
  if (!text.startsWith('---')) return null;
  const end = text.indexOf('\n---', 3);
  if (end === -1) return null;
  const block = text.slice(3, end);
  const out = {};
  // Keys are flat `key: value`; values may be quoted and may contain colons.
  const re = /^([A-Za-z_][A-Za-z0-9_-]*):[ \t]*(.*)$/gm;
  let m;
  while ((m = re.exec(block)) !== null) {
    let v = m[2].trim();
    if (
      (v.startsWith('"') && v.endsWith('"') && v.length > 1) ||
      (v.startsWith("'") && v.endsWith("'") && v.length > 1)
    ) {
      v = v.slice(1, -1);
    }
    out[m[1]] = v.replace(/\\"/g, '"');
  }
  return out;
}

/**
 * Resolves one .claude/agents/ entry to its AGENT.md path (relative to ROOT),
 * or null if the entry isn't an agent at all (e.g. `runs/`, a non-.md file).
 */
function resolveAgentMdPath(entryName) {
  const entryPath = join(CLAUDE_AGENTS_DIR, entryName);
  if (statSync(entryPath).isDirectory()) {
    const agentMd = join(entryPath, 'AGENT.md');
    return existsSync(agentMd) ? `.claude/agents/${entryName}/AGENT.md` : null;
  }
  return entryName.endsWith('.md') ? `.claude/agents/${entryName}` : null;
}

/**
 * Reads every agent under .claude/agents/ (folder-based `<name>/AGENT.md`, or a
 * flat `<name>.md`), pairs it with its tier from scripts/.agent-routing.json, and
 * returns the full agent roster. Problems (missing tier, orphaned tier entry)
 * are appended to `problems` rather than thrown, so the script can report every
 * issue in one pass instead of failing fast.
 */
function discoverAgents({ agentTiers }, problems) {
  const agents = [];
  for (const entry of readdirSync(CLAUDE_AGENTS_DIR).sort()) {
    const relPath = resolveAgentMdPath(entry);
    if (!relPath) continue; // e.g. runs/ (no AGENT.md) or an unrelated file

    const raw = readFileSync(join(ROOT, relPath), 'utf8');
    const fm = readFrontmatter(raw);
    if (!fm || !fm.name) continue; // e.g. ADLC-SPEC.md is a spec, not an agent

    const tier = agentTiers[fm.name];
    if (!tier) {
      problems.push(`agent "${fm.name}" (${relPath}) has no tier in scripts/.agent-routing.json → agentTiers`);
      continue;
    }

    agents.push({
      name: fm.name,
      file: relPath,
      description: fm.description || '',
      claudeModel: fm.model || '(unset — inherits)',
      tier,
    });
  }

  for (const name of Object.keys(agentTiers)) {
    if (!agents.some((a) => a.name === name)) {
      problems.push(`scripts/.agent-routing.json lists "${name}" but .claude/agents/ has no such agent (looked for ${name}/AGENT.md and ${name}.md)`);
    }
  }

  return agents;
}

// =============================================================================
// 3. Shared instructions text + per-format renderers
// =============================================================================
//
// `sharedInstructions()` is the ONE piece of prompt content every generated
// shim carries. It is plain text with no markup, so it can be embedded as-is
// inside Markdown, a TOML string, or any future format — every tool reads the
// same words. Renderers below only add the file-format "envelope" (YAML
// frontmatter + a Markdown heading, or TOML key/value pairs) and tool-specific
// metadata (model, reasoning effort, a model-verification caveat). Never put
// tool-specific wording inside `sharedInstructions()` — that would defeat the
// point of having one shared text.

function sharedInstructions(agent, tierLabel) {
  return `Role tier: ${tierLabel}.

Prompt source (authoritative — do not fork, do not edit): ${agent.file}

Load that file and follow it exactly. It is the shared prompt for every
supported CLI (Claude Code, Copilot CLI, Codex CLI). Editing it changes all of
them at once; editing this file changes nothing, because this file is
generated by scripts/sync-agent-routing.mjs.

Supporting contract: .claude/agents/ADLC-SPEC.md
Project context + Model Routing Matrix: AGENTS.md
Project identifiers (<project>, <package>, <group>): .aem-skills-config.yaml

Maven budget: at most 2 mvn invocations per ADLC run, owned exclusively by
auditron. Every other agent verifies statically via read/grep/glob.`;
}

/** Optional trailing note when a tool's per-agent `model` support is unverified. */
function modelCaveatNote(tool) {
  if (tool.modelVerified !== false) return '';
  return `

Note: per-agent model is unverified for ${tool.label} (documented for the IDEs
only). To guarantee a tier's model, launch with:
  ${tool.cliCommand ?? tool.label.toLowerCase()} --model="<model for this tier>"`;
}

/** JSON-encode a string for safe embedding in YAML (JSON is a YAML subset) and TOML. */
const encodeString = (s) => JSON.stringify(String(s).replace(/\s+/g, ' ').trim());

/**
 * One renderer per output *format* — NOT per tool. Every tool that shares a
 * format (e.g. two different CLIs that both read "YAML frontmatter +
 * Markdown body" agent files) reuses the same renderer function; only the
 * `tool` config object passed in changes what comes out (model, reasoning
 * effort, output directory, file suffix). To support a new LLM tool whose
 * agent files already look like one of these formats, add a `tools` entry in
 * scripts/.agent-routing.json with `"emit"` set to the matching key here — no code
 * change needed. Only a genuinely new file shape needs a new entry.
 */
const FORMAT_RENDERERS = {
  'frontmatter-md': (agent, tool, tierLabel) => `---
name: ${agent.name}
description: ${encodeString(agent.description)}
model: ${tool.models[agent.tier]}
---

# ${agent.name} — ${tierLabel} tier

${sharedInstructions(agent, tierLabel)}${modelCaveatNote(tool)}
`,

  toml: (agent, tool, tierLabel) => {
    // Codex's subagent schema requires name, description, and developer_instructions
    // on every custom agent file (see tool.docs). developer_instructions must be a
    // valid TOML multi-line basic string, so the shared prompt text is escaped
    // (backslashes, then any literal `"""`) before being wrapped in triple quotes —
    // otherwise Codex silently fails to parse the file and falls back to the
    // project-level default model in .codex/config.toml for every agent.
    const effort = tool.reasoningEffort?.[agent.tier];
    const reasoningLine = effort ? `model_reasoning_effort = ${encodeString(effort)}\n` : '';
    const instructions = `${sharedInstructions(agent, tierLabel)}${modelCaveatNote(tool)}`;
    const tomlSafeInstructions = instructions.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"');
    return `# GENERATED by scripts/sync-agent-routing.mjs — do not edit by hand.
# Prompt logic lives in ${agent.file}; edit that instead.
name = ${encodeString(agent.name)}
description = ${encodeString(agent.description)}
model = ${encodeString(tool.models[agent.tier])}
${reasoningLine}developer_instructions = """
${tomlSafeInstructions}
"""
`;
  },
};

/** Renders one agent's shim for one tool: { path, content }. */
function renderShim(agent, tool, tierLabels) {
  const render = FORMAT_RENDERERS[tool.emit];
  if (!render) return null; // caller reports the missing-renderer problem
  const dir = join(ROOT, ...(tool.outDir ?? []));
  const filename = `${agent.name}${tool.fileSuffix ?? ''}`;
  return { dir, filename, content: render(agent, tool, tierLabels[agent.tier]) };
}

// =============================================================================
// 4. Write shims to disk (idempotent by default — see FLAGS.force)
// =============================================================================

/**
 * For every (tool, agent) pair, decides whether to write, skip, or flag drift.
 * Returns { written[], skipped[], perToolDirs: Map<dir, Set<filename>> } so
 * the caller can both report results and know which files are "expected" for
 * orphan cleanup.
 */
function generateShims(agents, tools, tierLabels, problems) {
  const written = [];
  const skipped = [];
  const expectedFilesByDir = new Map(); // dir -> Set(filename), for orphan cleanup

  for (const [toolKey, tool] of Object.entries(tools)) {
    if (!tool.emit || tool.emit === 'none') continue; // e.g. Claude: nothing to generate

    for (const agent of agents) {
      if (!tool.models?.[agent.tier]) {
        problems.push(`tool "${toolKey}" has no model for tier "${agent.tier}" (needed by ${agent.name})`);
        continue;
      }

      const shim = renderShim(agent, tool, tierLabels);
      if (!shim) {
        problems.push(`tool "${toolKey}" declares emit "${tool.emit}" but no renderer is implemented`);
        continue;
      }

      if (!expectedFilesByDir.has(shim.dir)) expectedFilesByDir.set(shim.dir, new Set());
      expectedFilesByDir.get(shim.dir).add(shim.filename);

      const path = join(shim.dir, shim.filename);
      const existsOnDisk = existsSync(path);
      const onDiskContent = existsOnDisk ? readFileSync(path, 'utf8') : null;
      const isUpToDate = onDiskContent === shim.content;

      if (FLAGS.checkOnly) {
        // --check always compares content, regardless of --force, so CI can
        // still catch drift on files a normal run would otherwise skip.
        if (!isUpToDate) problems.push(`out of sync: ${displayPath(path)}`);
        continue;
      }

      if (isUpToDate) continue; // nothing to do either way

      if (existsOnDisk && !FLAGS.force) {
        // Idempotent default: never overwrite a shim that's already there.
        // Re-running this script without --force only creates missing files.
        skipped.push(path);
        continue;
      }

      mkdirSync(shim.dir, { recursive: true });
      writeFileSync(path, shim.content);
      written.push(path);
    }
  }

  return { written, skipped, expectedFilesByDir };
}

/**
 * Deletes shim files whose agent no longer exists in the roster. Like
 * overwriting, deletion only happens with --force; a plain run just reports
 * the orphan and leaves it in place.
 */
function pruneOrphans(expectedFilesByDir, problems, skipped, written) {
  for (const [dir, expectedFilenames] of expectedFilesByDir) {
    if (!existsSync(dir)) continue;
    for (const filename of readdirSync(dir)) {
      if (filename.startsWith('.') || expectedFilenames.has(filename)) continue;

      const path = join(dir, filename);
      if (FLAGS.checkOnly) problems.push(`orphan shim (no matching agent): ${displayPath(path)}`);
      else if (!FLAGS.force) skipped.push(`${path} (orphan — rerun with --force to remove)`);
      else {
        rmSync(path);
        written.push(`${path} (removed — orphan)`);
      }
    }
  }
}

// =============================================================================
// 5. Regenerate the Model Routing Matrix in AGENTS.md
// =============================================================================

function buildRoutingMatrixTable(agents, tools, tierLabels, adlcStages) {
  const toolList = Object.values(tools);
  const header = ['Agent', 'ADLC stage', 'Role tier', ...toolList.map((t) => t.label), 'Prompt source'];

  const modelCell = (agent, tool) => {
    if (tool.modelSource === 'frontmatter') return `\`${agent.claudeModel}\``;
    if (tool.reasoningEffort) return `\`${tool.models[agent.tier]}\` / \`${tool.reasoningEffort[agent.tier]}\``;
    return tool.models[agent.tier];
  };

  const rows = agents.map((agent) => {
    const cells = [
      `\`${agent.name}\``,
      adlcStages[agent.name] || '—',
      tierLabels[agent.tier],
      ...toolList.map((tool) => modelCell(agent, tool)),
      `[@${agent.file}](${agent.file})`,
    ];
    return `| ${cells.join(' | ')} |`;
  });

  return { header, rows };
}

function buildModelCaveats(tools) {
  return Object.values(tools)
    .filter((t) => t.modelVerified === false && t.modelCaveat)
    .map((t) => `> **⚠️ Unverified — ${t.label} per-agent model.** ${t.modelCaveat}`)
    .join('\n>\n');
}

function buildModelSlugSummary(tools) {
  return Object.values(tools)
    .filter((t) => t.emit && t.emit !== 'none')
    .map((t) => `${t.label} — ${[...new Set(Object.values(t.models))].map((m) => `\`${m}\``).join(', ')}`)
    .join('; ');
}

function buildRoutingMatrixMarkdown(agents, tools, tierLabels, adlcStages) {
  const { header, rows } = buildRoutingMatrixTable(agents, tools, tierLabels, adlcStages);
  const caveats = buildModelCaveats(tools);

  return `${MATRIX_BEGIN}
## Model Routing Matrix

**Single source of truth.** The agent roster and *all* prompt logic live in
[.claude/agents/](.claude/agents/) — one \`.md\` per agent, never duplicated. Role
tiers and the model each tool uses per tier live in
[scripts/.agent-routing.json](scripts/.agent-routing.json). Everything below, plus every file in
\`.github/agents/\` and \`.codex/agents/\`, is **generated** by
[scripts/sync-agent-routing.mjs](scripts/sync-agent-routing.mjs).

- **Add an agent:** drop \`.claude/agents/<name>.md\`, add one line to \`agentTiers\`, re-run the script.
- **Add another LLM tool:** add one \`tools\` entry (models per tier, pointing \`emit\` at an existing format), re-run. No per-agent files are hand-written.
- **Never edit** \`.github/agents/*\` or \`.codex/agents/*\` directly — they are overwritten.

\`\`\`bash
node scripts/sync-agent-routing.mjs           # create any missing shims + refresh this table
node scripts/sync-agent-routing.mjs --force   # also re-sync existing shims and prune orphans
node scripts/sync-agent-routing.mjs --check   # CI: fail if anything drifted (no writes)
\`\`\`

| ${header.join(' | ')} |
| ${header.map(() => '---').join(' | ')} |
${rows.join('\n')}

Role tiers are inferred from each agent's actual responsibilities, not its filename.
The lifecycle contract is [ADLC-SPEC.md](.claude/agents/ADLC-SPEC.md) (note: it lives
inside \`.claude/agents/\`, not \`.claude/\`).

### Per-tool routing mechanisms (verified)

| Tool | Repo-wide instructions | Per-agent definition | Per-agent model |
|---|---|---|---|
| Claude Code | \`CLAUDE.md\` → \`@AGENTS.md\` | \`.claude/agents/<name>.md\` (source of truth) | \`model:\` frontmatter — **supported** |
| Copilot CLI | \`AGENTS.md\`, \`.github/copilot-instructions.md\` | \`.github/agents/<name>.agent.md\` (generated) | \`model:\` frontmatter — **unverified for CLI**, see below |
| Codex CLI | \`AGENTS.md\` (project doc) | \`.codex/agents/<name>.toml\` (generated) | \`model\` + \`model_reasoning_effort\` — **supported** |

Per-tool scaffolding exists because each CLI only discovers agents in its own
directory and format; \`AGENTS.md\` is a standard for *instructions*, not for agent
*registration*. The generator makes that scaffolding free to maintain.

${caveats}

Model names/slugs in use: ${buildModelSlugSummary(tools)}.
${MATRIX_END}`;
}

/** Splices the generated matrix into AGENTS.md between its marker comments. */
function syncAgentsMd(agents, tools, tierLabels, adlcStages, problems, written) {
  const matrix = buildRoutingMatrixMarkdown(agents, tools, tierLabels, adlcStages);
  const current = readFileSync(AGENTS_MD, 'utf8');

  if (!current.includes(MATRIX_BEGIN) || !current.includes(MATRIX_END)) {
    problems.push(`AGENTS.md is missing the ${MATRIX_BEGIN} / ${MATRIX_END} markers — matrix not updated`);
    return;
  }

  const next = current.slice(0, current.indexOf(MATRIX_BEGIN)) + matrix + current.slice(current.indexOf(MATRIX_END) + MATRIX_END.length);
  if (next === current) return; // already in sync

  if (FLAGS.checkOnly) problems.push('out of sync: AGENTS.md routing matrix');
  else {
    writeFileSync(AGENTS_MD, next);
    written.push(AGENTS_MD);
  }
}

// =============================================================================
// 6. Report results and exit
// =============================================================================

function printReport({ agents, tools, written, skipped, problems }) {
  const emittingTools = Object.entries(tools).filter(([, t]) => t.emit && t.emit !== 'none');

  console.log(`agents discovered: ${agents.length}`);
  for (const a of agents) console.log(`  ${a.name.padEnd(20)} ${a.tier.padEnd(16)} claude=${a.claudeModel}`);
  console.log(`\ntools emitting shims: ${emittingTools.map(([k]) => k).join(', ') || '(none)'}`);

  if (!FLAGS.checkOnly) {
    console.log(`files written: ${written.length}`);
    for (const w of written) console.log(`  ${displayPath(w)}`);

    const skipNote = FLAGS.force ? '' : ' (pass --force to overwrite/remove)';
    console.log(`files already present, left untouched: ${skipped.length}${skipNote}`);
    for (const s of skipped) console.log(`  ${displayPath(s)}`);
  }

  if (problems.length) {
    console.error(`\n${FLAGS.checkOnly ? 'DRIFT/ERRORS' : 'PROBLEMS'} (${problems.length}):`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }
  console.log(FLAGS.checkOnly ? '\nin sync ✓' : '\nsync complete ✓');
}

// =============================================================================
// main
// =============================================================================

function main() {
  const problems = [];

  const { agentTiers, tierLabels, adlcStages, tools } = loadRoutingConfig();
  const agents = discoverAgents({ agentTiers }, problems);

  const { written, skipped, expectedFilesByDir } = generateShims(agents, tools, tierLabels, problems);
  pruneOrphans(expectedFilesByDir, problems, skipped, written);
  syncAgentsMd(agents, tools, tierLabels, adlcStages, problems, written);

  printReport({ agents, tools, written, skipped, problems });
}

main();